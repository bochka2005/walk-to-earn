#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════
# Файл: run.sh
# Назначение: Скрипт для запуска сервера одной командой.
# Что происходит: Создаёт виртуальное окружение (если нет),
# устанавливает пакеты и запускает uvicorn с FastAPI-приложением.
# ═══════════════════════════════════════════════════════════════

set -e                      # Остановить скрипт, если любая команда завершится ошибкой

cd "$(dirname "$0")"        # Перейти в папку, где лежит этот скрипт (корень проекта)

if [ ! -d venv ]; then      # Если папки venv не существует
    python3 -m venv venv    #   Создать виртуальное окружение Python
    source venv/bin/activate#   Активировать его
    pip install -r requirements.txt  # Установить зависимости из requirements.txt
else                        # Если папка venv уже есть
    source venv/bin/activate#   Просто активировать её
fi

exec uvicorn backend.main:app --host 0.0.0.0 --port 8000 --reload
# Запустить uvicorn:
#   backend.main:app    — файл backend/main.py, переменная app (FastAPI-приложение)
#   --host 0.0.0.0      — слушать на всех сетевых интерфейсах
#   --port 8000         — порт 8000
#   --reload            — перезагружать сервер при изменении кода (для разработки)
